// Generated deployment bridge: the weekly service remains the sole source of truth.
// No sender/config/recipient functions are copied into the public backend.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
function section(source, start, end) {
  const a = source.indexOf(start), b = source.indexOf(end, a + start.length);
  if (a < 0 || b < 0) throw new Error('READ_CORE_SOURCE_BOUNDARY_CHANGED');
  return source.slice(a, b).trim();
}
function build() {
  const code = fs.readFileSync(path.join(root, 'services/thu-tuan/Code.gs'), 'utf8');
  const transport = fs.readFileSync(path.join(root, 'services/thu-tuan/ZaloTransport.gs'), 'utf8');
  const result = '// GENERATED by tools/build-zalo-read-core.cjs; edit the source service, never this file.\n' + [
    section(code, "var THU_TUAN_TZ", 'function thuTuanEscapeHtml_'),
    section(code, 'function thuTuanSheet_', 'function thuTuanStorage_'),
    section(code, 'function thuTuanForKey_', '/** Basic mailbox syntax'),
    section(transport, 'function thuTuanZaloGraphemes_', '/** Drop all raw exceptions')
  ].join('\n\n') + '\n';
  new vm.Script(result);
  if (/function (?:gui|duyet|caiLich|thuTuan(?:Config|Storage|Adapter|Run|ZaloRequest)_)/.test(result))
    throw new Error('READ_CORE_HAS_WRITE_CAPABILITY');
  return result;
}
const target = path.join(root, 'backend/13a-thu-tuan-read-core.gs');
if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== build()) throw new Error('READ_CORE_STALE');
  } else fs.writeFileSync(target, build());
}
module.exports = { build, target };
